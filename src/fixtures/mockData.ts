// ─── Helper: get factory data ──────────────────────────────────────────────────
export function getFactory(id: string): Factory | undefined {
  return FACTORIES.find((f) => f.id === id);
}

export function getJob(id: string): Job | undefined {
  return JOBS.find((j) => j.id === id);
}

export function getBundle(id: string): Bundle | undefined {
  return BUNDLES.find((b) => b.id === id);
}

export function getBundleByCode(code: string): Bundle | undefined {
  return BUNDLES.find((b) => b.bundleCode === code);
}

export function getJobBundles(jobId: string): Bundle[] {
  return BUNDLES.filter((b) => b.jobId === jobId);
}

export function getUser(role: string): User | undefined {
  return DEMO_USERS.find((u) => u.role === role);
}
